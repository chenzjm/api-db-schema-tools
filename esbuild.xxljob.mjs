import esbuild from "esbuild";
import builtins from "builtin-modules";

/**
 * 只构建 xxl-job 子模块。
 *
 * ⚠️ 注意：本仓库的 `main.js` 是**手工维护**的 CJS（无编译步骤、改完 hot-reload 直接生效），
 * 所以这里的产物**只有** xxljob-bundle.cjs —— 绝不能把输出指向 main.js。
 * Schema Studio 的 main.js 里以 `require('./xxljob-bundle.cjs')` 加载它，
 * 拷不进来时 xxl-job 域自动降级不可用，接口 / 数据库两条链路不受影响。
 */
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
source: src/xxljob/ (TypeScript) — do not edit by hand
*/
`;

const watch = process.argv.includes("--watch");

const options = {
	banner: { js: banner },
	entryPoints: ["src/xxljob/bundle.ts"],
	outfile: "xxljob-bundle.cjs",
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: false,
	treeShaking: true,
	minify: false,
};

if (watch) {
	const ctx = await esbuild.context(options);
	await ctx.watch();
} else {
	await esbuild.build(options);
}
